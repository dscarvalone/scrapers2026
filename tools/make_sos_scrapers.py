"""Create counties/<name>/ scraper folders for every county that
tools/discover_enr.py found on the SOS-hosted ENR.

Each folder gets __init__.py, data/.gitkeep, README.md and a thin scraper.py
(same shape as counties/butler/scraper.py) pointing at that county's Nov 3,
2026 summary XML, then CSV. Existing scraper.py files are overwritten so
their URLs match discovery; other files in the folder are left alone.

Usage:
    python -m tools.make_sos_scrapers
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DISCOVERY = ROOT / "tools" / "enr_discovery.json"

SCRAPER = '''"""{county} County, OH election results by vote type (SOS-hosted Ohio ENR).

Generated by tools/make_sos_scrapers.py from tools/enr_discovery.json.
Election ID {eid} is the Nov 3, 2026 general (found {checked}).

The SOS ENR blocks plain HTTP, so this fetches through the Chrome window
opened by tools/sos_chrome.sh (see common/sos_browser.py). Run that first.

Usage:
    python -m counties.{folder}.scraper                # download live feed
    python -m counties.{folder}.scraper --file x.xml   # parse a local XML or CSV
"""

import sys
from pathlib import Path

from common.ohio_enr import run

URLS = {urls!r}

if __name__ == "__main__":
    sys.exit(run("{county}", URLS, Path(__file__).resolve().parent / "output",
                 expect_year="2026"))
'''

README = """# {county} County, OH

**Source:** SOS-hosted Ohio ENR, election ID {eid} (Nov 3, 2026 general).

- Summary XML: {xml}
- Summary CSV: {csv}{csv_note}

Vote types in the feed: {vtypes}.

These files sit behind a Cloudflare Turnstile check. The scraper reads them
through the Chrome window opened by `tools/sos_chrome.sh`
(`common/sos_browser.py`). Generated by `tools/make_sos_scrapers.py`.
"""


def folder_name(county: str) -> str:
    return county.lower().replace(" ", "_")


def main() -> int:
    found = {c: r for c, r in json.loads(DISCOVERY.read_text()).items() if r.get("election_id")}
    for county, r in sorted(found.items()):
        d = ROOT / "counties" / folder_name(county)
        (d / "data").mkdir(parents=True, exist_ok=True)
        (d / "__init__.py").touch()
        (d / "data" / ".gitkeep").touch()
        urls = [r["xml_url"]] + ([r["csv_url"]] if r.get("csv_ok") else [])
        (d / "scraper.py").write_text(SCRAPER.format(
            county=county, folder=folder_name(county), eid=r["election_id"],
            checked=r["checked_at"][:10], urls=urls))
        if not (d / "README.md").exists() or "make_sos_scrapers" in (d / "README.md").read_text():
            (d / "README.md").write_text(README.format(
                county=county, eid=r["election_id"], xml=r["xml_url"], csv=r["csv_url"],
                csv_note="" if r.get("csv_ok") else " (not available at discovery; XML only)",
                vtypes=", ".join(r.get("vote_types") or [])))
    print(f"Wrote scrapers for {len(found)} counties: {', '.join(sorted(found))}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
