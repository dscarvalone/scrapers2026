"""Generate COUNTIES.md: what is available for each of Ohio's 88 counties, and where.

Source of truth is counties.csv (plus the scraper mapping in
tools/build_method_workbook.py). Rerun after any change to either:

    python -m tools.make_counties_md
"""

from __future__ import annotations

import csv
from collections import Counter
from pathlib import Path

from tools.build_method_workbook import ACTIONS, EXPECTED, NOV3_ACTION, SCRAPED, SPLIT_EXPECTED

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "COUNTIES.md"

GROUPS = [
    ("n/a_scraped", "Itemized by vote method, scraper live"),
    ("yes_election_night", "Itemized, scraper waiting for the election-night link"),
    ("yes_nov3_precinct_only", "Split exists on election night, only in a precinct PDF (not scraped)"),
    ("likely_yes_election_night", "Likely split on election night (past election-night reports were)"),
    ("official_canvass_only", "Split only in the official canvass (~Nov 17-24), or only in some elections"),
    ("confirmed_no", "Totals only, confirmed (Nov 3 zero report and past reports)"),
    ("likely_no", "Totals only, likely (no past report was split)"),
    ("no_history_found", "Unknown (no past results found to check)"),
]
PLATFORM = {
    "ohio_enr_sos": "SOS-hosted ENR XML (liveresults.boe.ohio.gov)",
    "ohio_enr_county_hosted": "County-hosted ENR XML",
    "enhanced_voting": "Enhanced Voting JSON API",
    "enhanced_voting_xlsx": "Enhanced Voting Excel export",
    "clarity": "Clarity detail XML",
    "pdf_positional": "Results PDF (positional parser)",
    "pdf_dominion": "Results PDF (Dominion layout)",
}


def runs_in(county: str) -> str:
    if county not in SCRAPED:
        return ""
    return "GitHub Actions" if county in ACTIONS else "Local loop (Chrome)"


def folder(county: str) -> str:
    slug = county.lower().replace(" ", "_")
    return f"[counties/{slug}/](counties/{slug}/)" if (ROOT / "counties" / slug).is_dir() else ""


def main() -> int:
    rows = sorted(csv.DictReader((ROOT / "counties.csv").open(newline="")), key=lambda r: r["county"])
    by = Counter(r["history_split"] for r in rows)
    lines = [
        "# What is available for each county",
        "",
        "Generated by `python -m tools.make_counties_md` from `counties.csv`. Don't edit by hand.",
        "",
        "Goal: Ohio 2026 U.S. Senate results by county, split by vote method (Election Day, early",
        "in-person, mail, provisional). Every county has **totals** from the SOS statewide site",
        "(`results/senate_statewide_by_county.csv`); this page is about the **vote-method split**.",
        "",
        "| Group | Counties |",
        "|---|---|",
    ]
    for key, label in GROUPS:
        lines.append(f"| {label} | {by.get(key, 0)} |")
    lines += [
        "",
        "Column meanings: **Source** is where the split comes from; **Runs in** is where its scraper runs",
        "on election night (GitHub Actions on schedule, or `tools/local_loop.sh` on the owner's Mac",
        "through a real Chrome window, because SOS sites block scripts); **Buckets** is the label",
        "mapping (eday, evip = early in-person, vbm = mail, provisional; `early*` = the county gives",
        "only a combined early/absentee number); **Evidence** is the basis for the verdict, with the",
        "underlying document URLs in `tools/past_reports.json` and `tools/survey60_verdicts.json`.",
        "",
    ]
    for key, label in GROUPS:
        group = [r for r in rows if r["history_split"] == key]
        if not group:
            continue
        lines += [f"## {label} ({len(group)})", "",
                  f"Expected: {SPLIT_EXPECTED[key]}. Nov 3: {NOV3_ACTION[key]}.", ""]
        if key in ("n/a_scraped", "yes_election_night"):
            lines += ["| County | FIPS | Source | Runs in | Buckets | Caveats | Folder |", "|---|---|---|---|---|---|---|"]
            for r in group:
                c = r["county"]
                mapping, unmapped, assumption = SCRAPED[c]
                caveat = "; ".join(x for x in (f"Unassigned: {unmapped}" if unmapped else "", assumption) if x)
                lines.append(f"| {c} | {r['county_fips']} | {PLATFORM.get(r['platform'], r['platform'])} | "
                             f"{runs_in(c)} | {mapping} | {caveat} | {folder(c)} |")
        else:
            lines += ["| County | FIPS | Expected buckets | Results page | Evidence |", "|---|---|---|---|---|"]
            for r in group:
                c = r["county"]
                ev = " ".join(r["history_evidence"].split()).replace("|", "/")
                url = r["results_page"] or r["boe_url"]
                lines.append(f"| {c} | {r['county_fips']} | {EXPECTED.get(c, '')} | {url} | {ev} |")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"Wrote {OUT} ({len(rows)} counties)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
