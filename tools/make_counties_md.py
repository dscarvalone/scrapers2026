"""Generate COUNTIES.md: what is available for each of Ohio's 88 counties, and where.

Source of truth is counties.csv (plus the scraper mapping in
tools/build_method_workbook.py). Rerun after any change to either:

    python -m tools.make_counties_md
"""

from __future__ import annotations

import csv
from collections import Counter
from pathlib import Path

from tools.build_method_workbook import ACTIONS, EXPECTED, NOV3_ACTION, SCRAPED, SPLIT_EXPECTED

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "COUNTIES.md"

GROUPS = [
    ("n/a_scraped", "Itemized by vote method, scraper live"),
    ("yes_election_night", "Itemized, scraper waiting for the election-night link"),
    ("yes_nov3_precinct_only", "Split exists on election night, only in a precinct PDF (not scraped)"),
    ("likely_yes_election_night", "Likely split on election night (past election-night reports were)"),
    ("official_canvass_only", "Split only in the official canvass (~Nov 17-24), or only in some elections"),
    ("confirmed_no", "Totals only, confirmed (Nov 3 zero report and past reports)"),
    ("likely_no", "Totals only, likely (no past report was split)"),
    ("no_history_found", "Unknown (no past results found to check)"),
]
PLATFORM = {
    "ohio_enr_sos": "SOS-hosted ENR XML (liveresults.boe.ohio.gov)",
    "ohio_enr_county_hosted": "County-hosted ENR XML",
    "enhanced_voting": "Enhanced Voting JSON API",
    "enhanced_voting_xlsx": "Enhanced Voting Excel export",
    "clarity": "Clarity detail XML",
    "pdf_positional": "Results PDF (positional parser)",
    "pdf_dominion": "Results PDF (Dominion layout)",
}


def runs_in(county: str) -> str:
    if county not in SCRAPED:
        return ""
    return "GitHub Actions" if county in ACTIONS else "Local loop (Chrome)"


def folder(county: str) -> str:
    slug = county.lower().replace(" ", "_")
    return f"[counties/{slug}/](counties/{slug}/)" if (ROOT / "counties" / slug).is_dir() else ""


README = ROOT / "README.md"
EXPECTED_VOTES = ROOT / "tools" / "expected_votes.csv"
START, END = "<!-- COUNTY-SUMMARY:START -->", "<!-- COUNTY-SUMMARY:END -->"

# Plain-language status per history_split, for the README summary.
STATUS = {
    "n/a_scraped": "Yes",
    "yes_election_night": "Yes, once posted",
    "yes_nov3_precinct_only": "In precinct PDF only",
    "likely_yes_election_night": "Likely",
    "official_canvass_only": "No (canvass only)",
    "confirmed_no": "No",
    "likely_no": "No (likely)",
    "no_history_found": "Unknown",
}
GAP = {
    "yes_election_night": "Scraper waits for the election-night PDF link",
    "yes_nov3_precinct_only": "Split only in the precinct PDF; summing parser not built, so totals only for now",
    "likely_yes_election_night": "No scraper yet; the 8:30/9:30 PM recheck builds one if the Nov 3 file is split",
    "official_canvass_only": "Totals only on election night; split expected in the official canvass ~Nov 17-24",
    "confirmed_no": "No split published; totals only",
    "likely_no": "No past report split; totals only unless the Nov 3 format changes",
    "no_history_found": "Nothing to check in advance; recheck on Nov 3",
}
# Known gaps in counties that are scraped (beyond any unassigned labels).
SCRAPED_GAP = {
    "Hamilton": "Early not split into in-person vs mail; no provisional column",
    "Erie": "Early not split into in-person vs mail",
    "Paulding": "Early not split into in-person vs mail",
    "Allen": "Early not split into in-person vs mail",
    "Franklin": "Mail column (Absentee Ballots) is an inference",
    "Clark": "Mail column (Absentee Ballots) is an inference",
    "Lucas": "Mail column (Absentee Ballots) is an inference; no write-in line",
    "Miami": "Column order not yet verified on real votes",
    "Clermont": "Election-night file name unknown; scraper picks it from the results page "
                "(until then it reads the zero report). Check the loop log for 'parsing the zero report' after 7:30 PM",
}


def readme_summary(rows: list[dict]) -> str:
    exp = {r["county_fips"]: int(r["exp_total_votes"])
           for r in csv.DictReader(EXPECTED_VOTES.open(newline=""))}
    total = sum(exp.values())
    order = sorted(rows, key=lambda r: -exp[r["county_fips"]])

    def share(keys):
        return 100 * sum(exp[r["county_fips"]] for r in rows if r["history_split"] in keys) / total

    out = [START, "",
           "## County summary (largest expected vote first)", "",
           "Generated by `python -m tools.make_counties_md`; details per county in [COUNTIES.md](COUNTIES.md).",
           "Ordered by `exp_total_votes` from the DSCC election-night workbook's `county_raw` tab",
           "(saved in `tools/expected_votes.csv`). \"Split\" means Senate votes by method on election night.",
           "",
           "**Share of the expected statewide vote, by what we'll have:**", "",
           f"- **Split by method, scraper live or waiting for a link:** "
           f"{share({'n/a_scraped', 'yes_election_night'}):.1f}% "
           f"({sum(r['history_split'] in ('n/a_scraped', 'yes_election_night') for r in rows)} counties)",
           f"- **Maybe on election night (precinct PDF, likely, or unknown):** "
           f"{share({'yes_nov3_precinct_only', 'likely_yes_election_night', 'no_history_found'}):.1f}% "
           f"({sum(r['history_split'] in ('yes_nov3_precinct_only', 'likely_yes_election_night', 'no_history_found') for r in rows)} counties)",
           f"- **Gap until the official canvass (~Nov 17-24):** {share({'official_canvass_only'}):.1f}% "
           f"({sum(r['history_split'] == 'official_canvass_only' for r in rows)} counties)",
           f"- **Gap with no split expected (totals only):** {share({'confirmed_no', 'likely_no'}):.1f}% "
           f"({sum(r['history_split'] in ('confirmed_no', 'likely_no') for r in rows)} counties)",
           "",
           "**Before vs on Election Day (the split that matters most) covers every county:** directly "
           f"from the vote-type split for the {share({'n/a_scraped', 'yes_election_night'}):.1f}% above, "
           "and as a **first-drop estimate** for the rest (`common/timing.py`): Ohio counties release "
           "absentee and early ballots before any precinct, so a county's last report with 0 precincts "
           "in is its pre-Election-Day vote. The estimate fails for a county whose first report already "
           "includes precincts, and it needs the local loop running before the first results (~7:30 PM). "
           "Mail vs in-person is a bonus where the county reports it (`has_mail_inperson_split`).",
           "",
           "| # | County | Expected votes | % of state | Cumulative % | Split on election night | Before / on Election Day | Source (runs in) | Gap |",
           "|---|---|---|---|---|---|---|---|---|"]
    cum = 0.0
    for i, r in enumerate(order, 1):
        c, hs = r["county"], r["history_split"]
        v = exp[r["county_fips"]]
        cum += 100 * v / total
        if c in SCRAPED:
            where = "Actions" if c in ACTIONS else "local loop"
            src = f"{PLATFORM.get(r['platform'], r['platform']).split(' (')[0]}, {where}"
            gaps = []
            if c in ACTIONS and not (ROOT / "counties" / c.lower().replace(" ", "_") / "data" / "summary_wide.csv").exists():
                gaps.append("No committed data yet: needs one Actions run")
            if c in SCRAPED_GAP:
                gaps.append(SCRAPED_GAP[c])
            if SCRAPED[c][1]:
                gaps.append(f"Unassigned vote types: {SCRAPED[c][1]}")
            if hs == "yes_election_night":
                gaps.insert(0, GAP[hs])
            gap = "; ".join(gaps) or "None"
        else:
            src, gap = "Statewide totals only", GAP[hs]
            if r["boe_host"] == "county" and hs not in ("confirmed_no",):
                gap += ". County-hosted site: the Nov 3 recheck is manual"
        status = STATUS[hs]
        if status.startswith("No") or status == "Unknown" or status == "In precinct PDF only":
            status = f"**{status}**"
        timing_col = "Direct" if c in SCRAPED else "Estimate (first drop)"
        out.append(f"| {i} | {c} | {v:,} | {100 * v / total:.1f}% | {cum:.1f}% | {status} | {timing_col} | {src} | {gap} |")
    out += ["", END]
    return "\n".join(out)


def write_readme(section: str) -> None:
    text = README.read_text()
    if START in text and END in text:
        pre, rest = text.split(START, 1)
        post = rest.split(END, 1)[1]
        text = pre + section + post
    else:  # first time: insert after the "Start here" section
        anchor = "\n## Where things are"
        if anchor not in text:
            raise SystemExit("README has no '## Where things are' heading to insert before")
        text = text.replace(anchor, "\n" + section + "\n" + anchor, 1)
    README.write_text(text)


def main() -> int:
    rows = sorted(csv.DictReader((ROOT / "counties.csv").open(newline="")), key=lambda r: r["county"])
    write_readme(readme_summary(rows))
    print(f"Updated county summary in {README}")
    by = Counter(r["history_split"] for r in rows)
    lines = [
        "# What is available for each county",
        "",
        "Generated by `python -m tools.make_counties_md` from `counties.csv`. Don't edit by hand.",
        "",
        "Goal: Ohio 2026 U.S. Senate results by county, split by vote method (Election Day, early",
        "in-person, mail, provisional). Every county has **totals** from the SOS statewide site",
        "(`results/senate_statewide_by_county.csv`); this page is about the **vote-method split**.",
        "",
        "| Group | Counties |",
        "|---|---|",
    ]
    for key, label in GROUPS:
        lines.append(f"| {label} | {by.get(key, 0)} |")
    lines += [
        "",
        "Column meanings: **Source** is where the split comes from; **Runs in** is where its scraper runs",
        "on election night (GitHub Actions on schedule, or `tools/local_loop.sh` on the owner's Mac",
        "through a real Chrome window, because SOS sites block scripts); **Buckets** is the label",
        "mapping (eday, evip = early in-person, vbm = mail, provisional; `early*` = the county gives",
        "only a combined early/absentee number); **Evidence** is the basis for the verdict, with the",
        "underlying document URLs in `tools/past_reports.json` and `tools/survey60_verdicts.json`.",
        "",
    ]
    for key, label in GROUPS:
        group = [r for r in rows if r["history_split"] == key]
        if not group:
            continue
        lines += [f"## {label} ({len(group)})", "",
                  f"Expected: {SPLIT_EXPECTED[key]}. Nov 3: {NOV3_ACTION[key]}.", ""]
        if key in ("n/a_scraped", "yes_election_night"):
            lines += ["| County | FIPS | Source | Runs in | Buckets | Caveats | Folder |", "|---|---|---|---|---|---|---|"]
            for r in group:
                c = r["county"]
                mapping, unmapped, assumption = SCRAPED[c]
                caveat = "; ".join(x for x in (f"Unassigned: {unmapped}" if unmapped else "", assumption) if x)
                lines.append(f"| {c} | {r['county_fips']} | {PLATFORM.get(r['platform'], r['platform'])} | "
                             f"{runs_in(c)} | {mapping} | {caveat} | {folder(c)} |")
        else:
            lines += ["| County | FIPS | Expected buckets | Results page | Evidence |", "|---|---|---|---|---|"]
            for r in group:
                c = r["county"]
                ev = " ".join(r["history_evidence"].split()).replace("|", "/")
                url = r["results_page"] or r["boe_url"]
                lines.append(f"| {c} | {r['county_fips']} | {EXPECTED.get(c, '')} | {url} | {ev} |")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"Wrote {OUT} ({len(rows)} counties)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
