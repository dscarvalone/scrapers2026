"""Write counties/<folder>/scraper.py for an SOS-hosted county whose
election-night results PDF (www.boe.ohio.gov/<slug>/c/elecres/20261103results.pdf)
has a vote-method split in the U.S. Senate block.

Used by tools/recheck_zero_reports.py (--make-scrapers) and by hand:
    python -m tools.make_pdf_scraper "Logan" positional "Election Day, Absentee, Provisional"
Layouts: positional (ES&S / Electionware, by word position) or dominion.
Existing scraper.py files are not overwritten unless --force.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

TEMPLATE = '''"""{name} County, OH U.S. Senate results by vote type, from the county's
election-night PDF on its SOS-hosted BOE site.

Source: https://www.boe.ohio.gov/{slug}/c/elecres/20261103results.pdf
Columns in the Senate block when generated ({when}): {cols}.
Layout: {layout} (common/pdf_results.py). Generated by tools/make_pdf_scraper.py.
Fetched through the Chrome window opened by tools/sos_chrome.sh.

Usage:
    python -m counties.{folder}.scraper
    python -m counties.{folder}.scraper --file results.pdf
"""

import argparse
import sys
from pathlib import Path

from common.pdf_results import run
from common.sos_browser import fetch_file_via_page

NEEDS_LOCAL_CHROME = True  # picked up by tools/run_sos_counties.py
URL = "https://www.boe.ohio.gov/{slug}/c/elecres/20261103results.pdf"
PAGE = "https://www.boe.ohio.gov/{slug}/election-info/election-results/"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--file")
    args = ap.parse_args(argv)
    data = Path(args.file).read_bytes() if args.file else fetch_file_via_page(URL, PAGE)
    return run("{name}", "{layout}", data, Path(__file__).resolve().parent / "output", URL)


if __name__ == "__main__":
    sys.exit(main())
'''


def make(county: str, layout: str, cols: str, force: bool = False) -> Path:
    from datetime import datetime
    folder = county.lower().replace(" ", "_")
    slug = county.lower().replace(" ", "")
    d = ROOT / "counties" / folder
    (d / "data").mkdir(parents=True, exist_ok=True)
    (d / "__init__.py").touch()
    (d / "data" / ".gitkeep").touch()
    p = d / "scraper.py"
    if p.exists() and not force:
        print(f"{p} exists; not overwriting (use --force)", file=sys.stderr)
        return p
    p.write_text(TEMPLATE.format(name=county, slug=slug, folder=folder, layout=layout, cols=cols,
                                 when=datetime.now().strftime("%Y-%m-%d %H:%M")))
    return p


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if a != "--force"]
    if len(args) != 3:
        raise SystemExit(__doc__)
    print(make(*args, force="--force" in sys.argv))
