"""Seneca County, OH U.S. Senate results by vote type, from the county's
election-night PDF on its SOS-hosted BOE site.

Source: https://www.boe.ohio.gov/seneca/c/elecres/20261103results.pdf
Columns in the Senate block when generated (2026-11-03 00:39): Election Day, Absentee, Provisional, Early Vote.
Layout: positional (common/pdf_results.py). Generated by tools/make_pdf_scraper.py.
Fetched through the Chrome window opened by tools/sos_chrome.sh.

Usage:
    python -m counties.seneca.scraper
    python -m counties.seneca.scraper --file results.pdf
"""

import argparse
import sys
from pathlib import Path

from common.pdf_results import run
from common.sos_browser import fetch_file_via_page

NEEDS_LOCAL_CHROME = True  # picked up by tools/run_sos_counties.py
URL = "https://www.boe.ohio.gov/seneca/c/elecres/20261103results.pdf"
PAGE = "https://www.boe.ohio.gov/seneca/election-info/election-results/"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--file")
    args = ap.parse_args(argv)
    data = Path(args.file).read_bytes() if args.file else fetch_file_via_page(URL, PAGE)
    return run("Seneca", "positional", data, Path(__file__).resolve().parent / "output", URL)


if __name__ == "__main__":
    sys.exit(main())
